package main

import (
	"bytes"
	"encoding/json"
	"flag"
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"strings"
	"text/template"
)

type contract struct {
	Launcher struct {
		Package            string `json:"package"`
		MainActivity       string `json:"mainActivity"`
		InputKeyService    string `json:"inputKeyService"`
		HomeKeyService     string `json:"homeKeyService"`
		NowPlayingListener string `json:"nowPlayingListener"`
	} `json:"launcher"`
	Theme struct {
		Directory           string   `json:"directory"`
		ConfigFile          string   `json:"configFile"`
		MaxConfigBytes      int      `json:"maxConfigBytes"`
		WallpaperFile       string   `json:"wallpaperFile"`
		WallpapersDirectory string   `json:"wallpapersDirectory"`
		RevisionFile        string   `json:"revisionFile"`
		ImageExtensions     []string `json:"imageExtensions"`
		MaxWallpapers       int      `json:"maxWallpapers"`
		MaxWallpaperBytes   int      `json:"maxWallpaperBytes"`
	} `json:"theme"`
	ConfigKeys []configKey `json:"configKeys"`
}

type configKey struct {
	Name string `json:"name"`
	Type string `json:"type"`
	Min  *int   `json:"min"`
	Max  *int   `json:"max"`
}

var knownTypes = map[string]string{
	"bool":     "TypeBool",
	"int":      "TypeInt",
	"string":   "TypeString",
	"color":    "TypeColor",
	"date":     "TypeDate",
	"packages": "TypePackages",
	"strings":  "TypeStrings",
	"keycodes": "TypeKeycodes",
}

func main() {
	root := flag.String("root", "../..", "repository root")
	flag.Parse()
	definition, err := loadContract("contract.json")
	if err != nil {
		fail(err)
	}

	outputs := map[string]func(*contract) ([]byte, error){
		"apps/tvctl/internal/contract/contract_gen.go":                    renderGo,
		"apps/launcher/app/src/main/java/com/gathin/tvhome/Contract.java": renderJava,
	}

	for path, render := range outputs {
		data, err := render(definition)
		if err != nil {
			fail(fmt.Errorf("%s: %w", path, err))
		}
		if err := os.WriteFile(filepath.Join(*root, path), data, 0o644); err != nil {
			fail(err)
		}
	}
}

func fail(err error) {
	fmt.Fprintln(os.Stderr, "generate:", err)
	os.Exit(1)
}

func loadContract(path string) (*contract, error) {
	data, err := os.ReadFile(path)
	if err != nil {
		return nil, err
	}

	var parsed contract
	decoder := json.NewDecoder(bytes.NewReader(data))
	decoder.DisallowUnknownFields()
	if err := decoder.Decode(&parsed); err != nil {
		return nil, err
	}

	return &parsed, validate(&parsed)
}

func validate(definition *contract) error {
	seen := map[string]bool{}
	for _, key := range definition.ConfigKeys {
		if _, ok := knownTypes[key.Type]; !ok {
			return fmt.Errorf("config key %s: unknown type %q", key.Name, key.Type)
		}
		if (key.Type == "int") != (key.Min != nil && key.Max != nil) {
			return fmt.Errorf("config key %s: min and max go with type int only", key.Name)
		}
		if seen[key.Name] {
			return fmt.Errorf("config key %s: listed twice", key.Name)
		}
		seen[key.Name] = true
	}

	return nil
}

func camel(snake string) string {
	var b strings.Builder
	for _, part := range strings.Split(snake, "_") {
		b.WriteString(strings.ToUpper(part[:1]) + part[1:])
	}

	return b.String()
}

func upper(snake string) string {
	return strings.ToUpper(snake)
}

func quoteAll(values []string) string {
	quoted := make([]string, len(values))
	for i, value := range values {
		quoted[i] = fmt.Sprintf("%q", value)
	}

	return strings.Join(quoted, ", ")
}

var functions = template.FuncMap{
	"camel":    camel,
	"upper":    upper,
	"quoteAll": quoteAll,
	"goKey":    goConfigKey,
}

func goConfigKey(key configKey) string {
	constant := "Key" + camel(key.Name)
	fields := fmt.Sprintf("Name: %s, Type: %s", constant, knownTypes[key.Type])
	if key.Min != nil {
		fields += fmt.Sprintf(", Min: %d, Max: %d", *key.Min, *key.Max)
	}

	return fmt.Sprintf("%s: {%s},", constant, fields)
}

func render(name, text string, source *contract) ([]byte, error) {
	parsed := template.Must(template.New(name).Funcs(functions).Parse(text))

	var output bytes.Buffer
	if err := parsed.Execute(&output, source); err != nil {
		return nil, err
	}

	return output.Bytes(), nil
}

func renderGo(definition *contract) ([]byte, error) {
	source, err := render("go", goTemplate, definition)
	if err != nil {
		return nil, err
	}

	return format.Source(source)
}

func renderJava(definition *contract) ([]byte, error) {
	return render("java", javaTemplate, definition)
}

